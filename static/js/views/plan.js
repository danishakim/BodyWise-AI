// AI diet plan + exclusive Smart Swap, Puasa Mode and Kenduri Rebalancer.
import { api } from '../api.js';
import { store, addMeal, eventActive } from '../store.js';
import { html, mount, icon, toast, $, $$, fmt, localISO, addDays } from '../ui.js';

const WEEK = ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday'];
const SLOT_COLORS = { Breakfast: 'var(--gold)', Sahur: 'var(--sky)', Lunch: 'var(--primary)', Iftar: 'var(--accent)', Snack: 'var(--sky)', Moreh: 'var(--gold)', Dinner: 'var(--accent)' };
const FEASTS = [
  { name: 'Kenduri kahwin', kcal: 900 },
  { name: 'Hari Raya open house', kcal: 1200 },
  { name: 'Buffet dinner', kcal: 1000 },
  { name: 'Birthday party', kcal: 600 },
];
let selectedDay = WEEK[(new Date().getDay() + 6) % 7];
let generating = false;

export function render(root, ctx) {
  const s = store.get();
  if (!s.plan && !generating) { generate(root, ctx); return; }
  if (generating) { mount(root, thinking(s.prefs.puasa)); return; }

  if (!s.metrics && s.profile) ctx.refreshMetrics().then((x) => x && location.hash.startsWith('#/plan') && render(root, ctx));
  const plan = s.plan;
  const day = plan.days.find((d) => d.day === selectedDay) || plan.days[0];
  const target = plan.target_kcal;
  const pct = Math.min(100, (day.total_kcal / target) * 100);

  mount(root, html`
    <header class="page-head">
      <div>
        <h1>${s.prefs.puasa ? html`Your <em>Ramadan</em> plan` : html`Your <em>makan</em> plan`}</h1>
      </div>
      <div class="row">
        ${plan.source === 'gemini' ? html`<span class="badge ai">${icon.sparkle} Generated by Gemini</span>` : ''}
        <button class="btn btn-primary" id="regen">${icon.refresh} Regenerate</button>
      </div>
    </header>

    ${plan.notice ? html`<div class="alert" style="margin-bottom:16px">${icon.info}<span>${plan.notice}</span></div>` : ''}

    <section class="card" style="margin-bottom:16px">
      <div class="row" style="justify-content:space-between">
        <div class="chips" role="group" aria-label="Plan preferences">
          <button class="chip" data-pref="puasa" aria-pressed="${s.prefs.puasa}">${icon.moon} Puasa mode</button>
          <button class="chip" data-pref="vegetarian" aria-pressed="${s.prefs.vegetarian}">${icon.leaf} Vegetarian</button>
          <button class="chip" data-pref="halal" aria-pressed="${s.prefs.halal}">Halal</button>
        </div>
        <label class="row tiny" style="min-width:220px;flex:1;max-width:340px">${icon.wallet}<span style="white-space:nowrap">Budget <b id="bud">RM${s.prefs.budget_rm}</b>/day</span>
          <input type="range" id="budget" min="10" max="80" value="${s.prefs.budget_rm}" aria-label="Daily budget"></label>
      </div>
      <p class="tiny muted" id="pref-hint" style="margin-top:8px">Changed a preference? Tap <b>Regenerate</b> to apply it.</p>
    </section>

    <div class="day-tabs" role="tablist" aria-label="Days of the week">
      ${plan.days.map((d) => html`<button class="day-tab" role="tab" data-day="${d.day}" aria-selected="${d.day === day.day}">
        ${d.day.slice(0, 3)}<small class="num">${fmt.kcal(d.total_kcal)}</small><i class="dot ${d.on_target ? '' : 'off'}" title="${d.on_target ? 'On target' : 'Off target by more than 15%'}"></i></button>`)}
    </div>

    <section class="card" style="margin:12px 0 16px">
      <div class="grid grid-3" style="gap:20px">
        <div><div class="tiny muted">Calories</div><div class="big-number num">${fmt.kcal(day.total_kcal)}<small>/ ${fmt.kcal(target)}</small></div>
          <div class="bar-track" style="margin-top:8px"><div class="bar-fill ${day.on_target ? '' : 'gold'}" style="--v:${pct}%"></div></div></div>
        <div><div class="tiny muted">Protein</div><div class="big-number num">${day.total_protein_g}<small>g / ${s.metrics?.macros.protein_g ?? '–'}g</small></div></div>
        <div><div class="tiny muted">Estimated cost</div><div class="big-number num">${fmt.rm(day.total_cost_rm)}</div>
          <span class="badge ${day.total_cost_rm <= s.prefs.budget_rm ? 'good' : 'warn'}" style="margin-top:6px">${day.total_cost_rm <= s.prefs.budget_rm ? 'Within budget' : 'Over budget'}</span></div>
      </div>
    </section>

    <div class="grid grid-2">
      ${day.meals.map((meal, i) => html`
        <article class="card meal-card" style="--slot-color:${SLOT_COLORS[meal.slot] || 'var(--primary)'}">
          <div class="spread"><span class="slot-tag" style="color:var(--slot-color)">${meal.slot}</span>
            <span class="badge num">${fmt.kcal(meal.kcal)} kcal</span></div>
          <h3>${meal.name}</h3>
          <p class="muted tiny">${meal.description}</p>
          <div class="meal-meta"><span>Protein <b class="num">${meal.protein_g}g</b></span><span>Cost <b class="num">${fmt.rm(meal.cost_rm)}</b></span></div>
          <div class="row">
            <button class="btn btn-sm btn-primary" data-log="${i}">${icon.plus} Log it</button>
            <button class="btn btn-sm" data-swap="${i}">${icon.swap} Smart swap</button>
          </div>
          <div id="swaps-${i}"></div>
        </article>`)}
    </div>

    <div class="grid grid-2" style="margin-top:16px">
      <section class="card">
        <div class="card-title">${icon.sparkle} Tips for you</div>
        <p style="margin-bottom:10px">${plan.summary}</p>
        <ul class="stack" style="padding-left:18px;margin:0;gap:6px">${plan.tips.map((t) => html`<li>${t}</li>`)}</ul>
      </section>
      ${kenduriCard(s)}
    </div>`);

  // ---- events ----
  $('#regen', root).addEventListener('click', () => generate(root, ctx));
  $$('[data-day]', root).forEach((b) => b.addEventListener('click', () => { selectedDay = b.dataset.day; render(root, ctx); }));
  $$('[data-pref]', root).forEach((b) => b.addEventListener('click', () => {
    const key = b.dataset.pref;
    const prefs = { ...store.get().prefs, [key]: !store.get().prefs[key] };
    store.set({ prefs });
    b.setAttribute('aria-pressed', String(prefs[key]));
    $('#pref-hint', root).style.color = 'var(--accent)';
  }));
  const budget = $('#budget', root);
  budget.addEventListener('input', () => { $('#bud', root).textContent = `RM${budget.value}`; });
  budget.addEventListener('change', () => { store.set({ prefs: { ...store.get().prefs, budget_rm: Number(budget.value) } }); $('#pref-hint', root).style.color = 'var(--accent)'; });

  $$('[data-log]', root).forEach((b) => b.addEventListener('click', () => {
    const meal = day.meals[Number(b.dataset.log)];
    addMeal({ name: meal.name, kcal: meal.kcal, protein: meal.protein_g, slot: meal.slot, source: 'plan' });
    toast(`Logged ${meal.name} (${meal.kcal} kcal)`);
  }));

  $$('[data-swap]', root).forEach((b) => b.addEventListener('click', async () => {
    const i = Number(b.dataset.swap);
    const meal = day.meals[i];
    const box = $(`#swaps-${i}`, root);
    if (box.childElementCount) { box.innerHTML = ''; return; }
    b.disabled = true;
    try {
      const { swaps } = await api.swap(meal.slot, meal.kcal, store.get().prefs.vegetarian, meal.name);
      mount(box, swaps.length ? html`<div class="swap-list">
        <span class="tiny muted"><b>Lighter local swaps</b> that keep you full</span>
        ${swaps.map((sw, j) => html`<div class="swap-item"><span>${sw.name} <span class="muted num">· ${sw.kcal} kcal</span></span>
          <span class="row"><span class="save num">−${sw.saves_kcal}</span><button class="btn btn-sm" data-use="${j}">Use</button></span></div>`)}
      </div>` : html`<div class="swap-list tiny">Already a light choice. No lighter swap needed! 👍</div>`);
      $$('[data-use]', box).forEach((u) => u.addEventListener('click', () => applySwap(day.day, i, swaps[Number(u.dataset.use)], root, ctx)));
    } catch (err) { toast(err.message, 'error'); }
    b.disabled = false;
  }));

  bindKenduri(root, ctx);
}

function applySwap(dayName, index, sw, root, ctx) {
  const { plan } = store.get();
  const days = plan.days.map((d) => {
    if (d.day !== dayName) return d;
    const meals = d.meals.map((m, i) => (i !== index ? m : {
      slot: m.slot, name: sw.name, description: `Smart swap: saves ${sw.saves_kcal} kcal vs ${m.name}.`,
      kcal: sw.kcal, protein_g: sw.protein, cost_rm: sw.rm,
    }));
    const total = meals.reduce((a, m) => a + m.kcal, 0);
    return {
      ...d, meals, total_kcal: total,
      total_protein_g: meals.reduce((a, m) => a + m.protein_g, 0),
      total_cost_rm: Math.round(meals.reduce((a, m) => a + m.cost_rm, 0) * 100) / 100,
      on_target: Math.abs(total - plan.target_kcal) <= plan.target_kcal * 0.15,
    };
  });
  store.set({ plan: { ...plan, days } });
  toast(`Swapped in ${sw.name}`);
  render(root, ctx);
}

async function generate(root, ctx) {
  const s = store.get();
  generating = true;
  mount(root, thinking(s.prefs.puasa));
  try {
    const { plan, metrics } = await api.plan(s.profile, s.prefs);
    store.set({ plan, metrics });
    toast(plan.source === 'gemini' ? 'Fresh AI plan ready!' : 'Plan ready (demo mode)');
  } catch (err) {
    toast(err.message, 'error');
  } finally {
    generating = false;
  }
  if (location.hash.startsWith('#/plan')) {
    if (store.get().plan) {
      render(root, ctx);
    } else {
      mount(root, html`<div class="card thinking"><p>Couldn't build a plan.</p><button class="btn btn-primary" id="retry">${icon.refresh} Try again</button></div>`);
      $('#retry', root).addEventListener('click', () => generate(root, ctx));
    }
  }
}

